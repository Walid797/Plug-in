// Build Hoshmand Photo Studio into a fully self-contained offline folder.
//   node tools/build.mjs [--dev]
// Output (committed so end users never need Node):
//   app/app.js, app/app.css, app/build-info.json   – classic script bundle (works from file:// too)
//   vendor/…                                         – local copies of fonts, MediaPipe and ONNX Runtime
//   sw.js                                            – service worker with a generated precache list
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dev = process.argv.includes('--dev');
const nm = (...p) => path.join(root, 'node_modules', ...p);

async function sha256File(file) {
  return createHash('sha256').update(await fs.readFile(file)).digest('hex');
}

async function copy(src, dest) {
  await fs.mkdir(path.dirname(dest), { recursive: true });
  await fs.copyFile(src, dest);
}

